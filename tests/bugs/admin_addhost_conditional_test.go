package bugs

import (
	"encoding/json"
	"os/exec"
	"path/filepath"
	"testing"
)

// TestADMIN_AddHostDisabledFeaturesStayEmpty checks that disabled toggles do
// not inject empty PHP/Git/Auth blocks into the generated host config.
func TestADMIN_AddHostDisabledFeaturesStayEmpty(t *testing.T) {
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node not installed")
	}
	cwd, err := filepath.Abs(".")
	if err != nil {
		t.Fatal(err)
	}
	builder, err := filepath.Abs(filepath.Join(cwd, "..", "..", "internal", "operation", "admin", "js", "host-builder.js"))
	if err != nil {
		t.Fatal(err)
	}
	script := `
import { buildHostConfig } from 'file://` + filepath.ToSlash(builder) + `';
const web = (extra) => buildHostConfig({
  domain:'example.test', host_type:'web',
  routes:[{path:'/', engineData:Object.assign({web_static_on:true, web_root:'/tmp/site'}, extra)}]
});
const proxy = (extra) => buildHostConfig({
  domain:'example.test', host_type:'proxy',
  routes:[{path:'/', engineData:Object.assign({
    lb_strategy:'round_robin',
    backends_list: JSON.stringify([{address:'http://127.0.0.1:9000', weight:1}])
  }, extra)}]
});
let enabledPHPFailed = false;
try { web({php_enabled:true, php_address:''}); } catch { enabledPHPFailed = true; }
console.log(JSON.stringify({
  disabledPHP: web({php_enabled:false, php_address:''}),
  disabledGit: web({git_enabled:false, git_url:''}),
  disabledJWT: proxy({jwt_enabled:false, jwt_secret:''}),
  enabledPHPFailed,
  serverless: buildHostConfig({
    domain:'example.test', host_type:'serverless',
    routes:[{path:'/', engineData:{
      serverless_workers: JSON.stringify([{name:'worker', command:['node','worker.js']}])
    }}]
  })
}));
`
	out, err := exec.Command(node, "--input-type=module", "-e", script).Output()
	if err != nil {
		t.Fatalf("node host-builder: %v", err)
	}
	var got map[string]json.RawMessage
	if err := json.Unmarshal(out, &got); err != nil {
		t.Fatal(err)
	}
	php := string(got["disabledPHP"])
	git := string(got["disabledGit"])
	jwt := string(got["disabledJWT"])
	for name, blob := range map[string]string{"php": php, "git": git, "jwt": jwt} {
		if jsonContains(blob, `"php"`) || jsonContains(blob, `"git"`) || jsonContains(blob, `"jwt_auth"`) {
			t.Errorf("disabled %s feature leaked into config: %s", name, blob)
		}
	}
	var failed bool
	if err := json.Unmarshal(got["enabledPHPFailed"], &failed); err != nil || !failed {
		t.Fatalf("PHP enabled without address should fail, got %s", got["enabledPHPFailed"])
	}
	var sl struct {
		Routes []struct {
			Serverless struct {
				Workers []struct {
					Command []string `json:"command"`
				} `json:"workers"`
			} `json:"serverless"`
		} `json:"routes"`
	}
	if err := json.Unmarshal(got["serverless"], &sl); err != nil {
		t.Fatal(err)
	}
	if len(sl.Routes) != 1 || len(sl.Routes[0].Serverless.Workers) != 1 ||
		len(sl.Routes[0].Serverless.Workers[0].Command) != 2 {
		t.Fatalf("serverless worker command lost: %+v", sl)
	}
}

func jsonContains(blob, needle string) bool {
	// Avoid importing a decoder just for a substring check; the JSON fixtures
	// here are generated by the builder and contain no escaped false positives.
	for i := 0; i+len(needle) <= len(blob); i++ {
		if blob[i:i+len(needle)] == needle {
			return true
		}
	}
	return false
}
